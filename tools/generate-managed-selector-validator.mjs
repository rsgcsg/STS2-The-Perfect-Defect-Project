import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const requireSdk = createRequire(path.join(root, "components/connector/sdk/typescript/package.json"));
const ts = requireSdk("typescript");
export const generatedPath = "components/host-runtime/src/native-card-selection.generated.mjs";

// A shipped Host cannot import unpublished SDK exports. Distribute this pure
// validator as generated ESM, keeping the canonical contract in Connector.
export function managedSelectorArtifact(workspaceRoot = root) {
  const directory = path.join(workspaceRoot, "components/connector/sdk/typescript/src");
  const source = readFileSync(path.join(directory, "nativeCardSelection.ts"), "utf8").replace(/\r\n/gu, "\n");
  const json = readFileSync(path.join(directory, "json.ts"), "utf8").replace(/\r\n/gu, "\n");
  const syntax = ts.createSourceFile("json.ts", json, ts.ScriptTarget.ES2022, true);
  const helper = syntax.statements.filter(node => ts.isFunctionDeclaration(node)
    && node.name?.text === "isJsonObject");
  const importLine = 'import { isJsonObject } from "./json.js";';
  if (helper.length !== 1 || !source.startsWith(importLine))
    throw new Error("Managed selector generation requires its exact pure JSON helper");
  const canonical = helper[0].getText(syntax) + "\n" + source.slice(importLine.length);
  const compiled = ts.transpileModule(canonical, { compilerOptions: {
    target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, newLine: ts.NewLineKind.LineFeed,
    removeComments: true
  }}).outputText;
  if (/\b(?:import|require)\s*[("'{]/u.test(compiled))
    throw new Error("Generated Managed selector validator must be self-contained");
  return "// Generated by tools/generate-managed-selector-validator.mjs; do not edit.\n"
    + "// Canonical owner: Connector SDK nativeCardSelection.ts and isJsonObject.\n"
    + `// Canonical SHA256: ${createHash("sha256").update(canonical).digest("hex")}\n`
    + compiled;
}

export function managedSelectorArtifactErrors(workspaceRoot = root) {
  try {
    return readFileSync(path.join(workspaceRoot, generatedPath), "utf8") === managedSelectorArtifact(workspaceRoot)
      ? [] : ["Generated Managed selector validator is stale; run tools/generate-managed-selector-validator.mjs"];
  } catch (error) { return [`Managed selector generated artifact unavailable: ${error.message}`]; }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const errors = managedSelectorArtifactErrors();
    if (errors.length) throw new Error(errors.join("\n"));
  } else writeFileSync(path.join(root, generatedPath), managedSelectorArtifact());
}
